create or replace function match_intent(q text, surf text)
returns table(intent text, sim float) language sql stable as $$
  select intent, max(1 - (embedding <=> q::vector)) as sim from chat_intents
  where surface = surf and embedding is not null group by intent order by 2 desc limit 5;
$$;